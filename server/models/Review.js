import mongoose from "mongoose";

const reviewSchema = new mongoose.Schema(
  {
    student: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    book: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Book",
      required: true,
    },

    rating: {
      type: Number,
      required: true,
      min: 1,
      max: 5,
    },

    comment: {
      type: String,
      trim: true,
      maxlength: 1000,
    },
  },
  {
    timestamps: true,
  }
);

// Enforce one review per student per book and optimize review lookups
reviewSchema.index({ student: 1, book: 1 }, { unique: true });
reviewSchema.index({ book: 1 });
reviewSchema.index({ student: 1 });

export default mongoose.model("Review", reviewSchema);